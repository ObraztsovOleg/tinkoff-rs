//! TLS для HTTP-клиентов (ИИ-модели, документы, векторы).
//!
//! reqwest подключён без собственного криптопровайдера: весь стенд работает на
//! одном провайдере rustls (ring), который уже используют gRPC и база. Два
//! провайдера в одном процессе rustls не допускает, а без установленного
//! провайдера reqwest не создаст клиента — поэтому каждый клиент строится через
//! [`http_client`], который один раз ставит ring провайдером процесса.

/// Построитель HTTP-клиента с установленным провайдером TLS.
pub(crate) fn http_client() -> reqwest::ClientBuilder {
    // Повторная установка возвращает ошибку «уже установлен» — это нормально.
    let _ = rustls::crypto::ring::default_provider().install_default();
    reqwest::Client::builder()
}
